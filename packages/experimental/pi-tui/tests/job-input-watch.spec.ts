import { afterEach, describe, expect, it, vi } from 'vitest'
import { JobId } from '@deepseek-ai/dsh-jobs'
import { JobInputWatch } from '../src/core/job-input-watch.ts'

describe('background job input observation', () => {
  afterEach(() => vi.useRealTimers())

  it('warns after split ANSI prompt output and quiet time', () => {
    vi.useFakeTimers()
    const id = JobId('ssh-1')
    const changed = vi.fn()
    const watch = new JobInputWatch(15000, changed)
    watch.output(id, '\x1b[31mPass')
    watch.activity(id)
    watch.output(id, 'word:\x1b[0m')
    expect(changed).toHaveBeenLastCalledWith(id, false)
    vi.advanceTimersByTime(14999)
    expect(changed).not.toHaveBeenCalledWith(id, true)
    vi.advanceTimersByTime(1)
    expect(changed).toHaveBeenLastCalledWith(id, true)
    watch.dispose()
  })

  it('recognizes a carriage-return redraw but ignores silence and ordinary output', () => {
    vi.useFakeTimers()
    const id = JobId('pwsh-1')
    const changed = vi.fn()
    const watch = new JobInputWatch(100, changed)
    vi.advanceTimersByTime(1000)
    watch.output(id, 'progress 10%\rPassword:\n')
    vi.advanceTimersByTime(100)
    expect(changed).toHaveBeenLastCalledWith(id, true)
    changed.mockClear()
    watch.output(id, 'working')
    vi.advanceTimersByTime(1000)
    expect(changed).toHaveBeenLastCalledWith(id, false)
    expect(changed).not.toHaveBeenCalledWith(id, true)
    watch.dispose()
  })

  it('recognizes sudo and SSH-key credential prompts', () => {
    vi.useFakeTimers()
    const sudo = JobId('sudo-1')
    const ssh = JobId('ssh-key-1')
    const changed = vi.fn()
    const watch = new JobInputWatch(100, changed)
    watch.output(sudo, '[sudo] password for user:')
    watch.output(ssh, "Enter passphrase for key 'id_ed25519':")
    vi.advanceTimersByTime(100)
    expect(changed).toHaveBeenCalledWith(sudo, true)
    expect(changed).toHaveBeenCalledWith(ssh, true)
    watch.dispose()
  })

  it('cancels pending warnings on progress, removal, and disposal', () => {
    vi.useFakeTimers()
    const first = JobId('bash-1')
    const second = JobId('kali-1')
    const changed = vi.fn()
    const watch = new JobInputWatch(100, changed)
    watch.output(first, '[Y/n]')
    watch.clear(first)
    vi.advanceTimersByTime(100)
    expect(changed).not.toHaveBeenCalledWith(first, true)
    watch.output(second, 'press Enter to continue')
    watch.dispose()
    vi.advanceTimersByTime(100)
    expect(changed).not.toHaveBeenCalledWith(second, true)
  })

  it('does not join prompt fragments across a lost-output gap', () => {
    vi.useFakeTimers()
    const id = JobId('lossy-1')
    const changed = vi.fn()
    const watch = new JobInputWatch(100, changed)
    watch.output(id, 'Pass')
    watch.reset(id)
    watch.output(id, 'word:')
    vi.advanceTimersByTime(100)
    expect(changed).not.toHaveBeenCalledWith(id, true)
    watch.dispose()
  })

  it('clears an active warning immediately when output arrives', () => {
    vi.useFakeTimers()
    const id = JobId('active-1')
    const changed = vi.fn()
    const watch = new JobInputWatch(100, changed)
    watch.output(id, 'Password:')
    vi.advanceTimersByTime(100)
    expect(changed).toHaveBeenLastCalledWith(id, true)
    watch.activity(id)
    expect(changed).toHaveBeenLastCalledWith(id, false)
    vi.advanceTimersByTime(100)
    expect(changed).not.toHaveBeenLastCalledWith(id, true)
    watch.dispose()
  })
})
